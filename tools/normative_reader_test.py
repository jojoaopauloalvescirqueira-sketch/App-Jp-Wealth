def digest(data):
    return hashlib.sha256(data).hexdigest()


def prepare(context):
    install_bootstrap(context)
    context.add_init_script(TRACKING)
    context._nr_console_errors = []
    context.on('console', lambda msg: context._nr_console_errors.append({'text': msg.text, 'location': msg.location}) if msg.type == 'error' else None)


def boot(browser, url, viewport=None, accepted=True, service_workers='allow'):
    context, page, observed = dashboard_boot(browser, url, viewport=viewport, prepare_context=prepare, service_workers=service_workers)
    wait_bootstrap(page)
    page.evaluate(SEED, {'version': 'V11.0+JPW-ANNEX-T03', 'accepted': accepted})
    page.evaluate("closeModal();if(typeof closeSettings==='function')closeSettings();")
    return context, page, observed


def navigate(page):
    assert page.evaluate("JPWNavigation.navigate('tools-normative')"), 'Normative route rejected'
    page.wait_for_function("!jpwNormativePage.hidden && !jpwNormativePage.inert")


def ready(page, number=None):
    try:
        page.wait_for_function("() => JPWNormativeReader.snapshot().verified && JPWNormativeReader.snapshot().renderedPage!==null && jpwNormativePage.getAttribute('aria-busy')==='false'", timeout=45000)
        if number is not None:
            page.wait_for_function("n => JPWNormativeReader.snapshot().renderedPage===n && jpwNormativePage.getAttribute('aria-busy')==='false'", arg=number, timeout=45000)
    except Exception:
        print(json.dumps(page.evaluate("({snapshot:JPWNormativeReader.snapshot(),status:nrStatus.textContent,integrity:nrIntegrity.textContent,busy:jpwNormativePage.getAttribute('aria-busy'),hidden:jpwNormativePage.hidden})"),ensure_ascii=False),flush=True)
        raise


def go(page, number):
    page.locator('#nrPage').fill(str(number))
    page.locator('#nrPage').press('Enter')
    ready(page, number)


def pixels(page):
    return page.evaluate("""() => {const c=nrPageHost.querySelector('canvas');if(!c)return null;const data=c.getContext('2d').getImageData(0,0,c.width,c.height).data;let ink=0;for(let i=0;i<data.length;i+=388)if(data[i]<240||data[i+1]<240||data[i+2]<240)ink++;const spans=[...nrPageHost.querySelectorAll('.textLayer span:not(.markedContent)')];return {width:c.width,height:c.height,ink,spans:spans.length,font:spans.length?parseFloat(getComputedStyle(spans[0]).fontSize):0}}""")


def unchanged(page, before):
    after = page.evaluate(SNAPSHOT)
    for field in ('state', 'storage', 'onboarding', 'history', 'finance'):
        assert after[field] == before[field], ('reader changed protected synthetic state', field)
    assert after['writes'] == before['writes'], 'reader wrote financial/local storage'


def source_checks():
    original = (ROOT / PDF).read_bytes()
    assert len(original) == 1499074 and digest(original) == SHA
    payload = json.loads((ROOT / PAYLOAD).read_text().split('window.JPW_NORMATIVE_STATUTE = ', 1)[1].rstrip(';\n'))
    assert payload['id'] == 'estatuto-v11' and payload['version'] == 'V11.0'
    assert payload['path'] == PDF and payload['bytes'] == len(original) and payload['sha256'] == SHA
    assert base64.b64decode(payload['base64']) == original, 'generated bytes differ from original'
    portable = (ROOT / 'dist/JP_Wealth_Risk_Terminal_V9.1_PORTABLE.html').read_text()
    embedded = re.search(r'window\.JPW_NORMATIVE_STATUTE = (\{[^\n]+\});\n', portable)
    assert embedded and json.loads(embedded.group(1)) == payload, 'portable payload differs'
    source = (ROOT / ADAPTER).read_text()
    assert not re.search(r'https?://|localStorage|sessionStorage|\bsave\(|\bS\.', source), 'unexpected external/storage access in reader'
    assert 'isEvalSupported:false' in source and 'enableXfa:false' in source
    return original


