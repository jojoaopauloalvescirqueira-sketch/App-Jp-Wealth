                unchanged(page,before)
                assert page.evaluate('S.onboarding.consentAccepted') is False
                assert not observed['pageerror'] and not observed['console'], observed
                checks.append({'scenario':'pending_consent_open_search_download_preserved','result':'PASS'})
                context.close()
                # Genuine missing-document response is visible and blocks all
                # original actions until a successful retry. Its sole expected
                # browser console entry is attributed to this injected 404.
                # Block SW only for HTTP error fixtures so their corrupt/404
                # responses cannot race the actual SW precache and claim phase.
                # Nominal offline and corrupted-cache checks use the real SW.
                context, page, observed = boot(browser, url, service_workers='block')
                before=page.evaluate(SNAPSHOT)
                context.route('**/' + PDF, lambda route: route.fulfill(status=404, content_type='text/plain', body='Synthetic unavailable document'))
                navigate(page)
                page.wait_for_function("nrIntegrity.dataset.state==='error' && nrStatus.textContent.includes('não está disponível')")
                assert page.locator('#nrDownload').is_disabled() and page.locator('#nrOriginal').get_attribute('aria-disabled')=='true'
                assert not page.locator('#nrPageHost canvas').count()
                assert not page.evaluate("__normativeWorkers.some(w=>w.name==='JPW Estatuto V11 local')")
                assert len(context._nr_console_errors)==1 and PDF in context._nr_console_errors[0]['location']['url'] and '404' in context._nr_console_errors[0]['text'], context._nr_console_errors
                context.unroute('**/' + PDF);page.locator('#nrRetry').click();ready(page,1)
                unchanged(page,before)
                assert not observed['pageerror'] and len(observed['console'])==1,observed
                checks.append({'scenario':'missing_document_404_blocked_then_retry','result':'PASS','expectedInjected404Console':1})
                context.close()
                # Failure before worker creation, followed by real recovery.
                context, page, observed = boot(browser, url, service_workers='block')
                bad = original[:-1] + bytes([original[-1] ^ 1])
                context.route('**/' + PDF, lambda route: route.fulfill(status=200, content_type='application/pdf', body=bad))
                navigate(page)
                page.wait_for_function("nrIntegrity.dataset.state==='error' && nrStatus.textContent.includes('integridade')")
                assert not page.locator('#nrPageHost canvas').count()
                assert not page.evaluate("__normativeWorkers.some(w=>w.name==='JPW Estatuto V11 local')")
                context.unroute('**/' + PDF)
                page.locator('#nrRetry').click();ready(page, 1)
                checks.append({'scenario': 'wrong_hash_blocked_before_worker_then_retry', 'result': 'PASS'})
                page.evaluate("JPWNormativeReader.leave();window.__savedNormativeWorker=Worker;window.Worker=class{constructor(){throw new Error('Synthetic unavailable worker')}};JPWNormativeReader.enter()")
                page.wait_for_function("nrIntegrity.dataset.state==='verified' && nrStatus.textContent.includes('leitor local não pôde')")
                assert page.locator('#nrDownload').is_enabled() and page.locator('#nrOriginal').get_attribute('aria-disabled') == 'false'
                assert not page.locator('#nrPageHost canvas').count()
                with page.expect_download() as pending:page.locator('#nrDownload').click()
                assert digest(Path(pending.value.path()).read_bytes()) == SHA
                page.evaluate('() => {window.Worker=window.__savedNormativeWorker}')
